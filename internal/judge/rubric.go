/*
Package judge is what a judge run knows about its rubric (NT-016): the declaration, the
codes the judge answers with, the closed parser, the prompt and the sealed objects.

Pure: no I/O and no clock. The salt is generated by whoever opens a judge run and stored as
that run's content; this package only uses it.
*/
package judge

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"strconv"
)

// OutputType is the shape of a judge's verdict.
type OutputType string

const (
	OutputPassFail OutputType = "pass_fail"
	OutputScore    OutputType = "score"
	OutputCategory OutputType = "category"
)

// Output is the declared verdict and its pass criterion. Each field is a pointer or a
// slice so that its presence is what was declared: a zero is a value, and a field a type
// does not take is refused even when it is zero or empty.
type Output struct {
	Type       OutputType `json:"type"`
	Min        *int       `json:"min,omitempty"`
	Max        *int       `json:"max,omitempty"`
	Threshold  *int       `json:"threshold,omitempty"`
	Categories []string   `json:"categories,omitempty"`
	Passing    []string   `json:"passing,omitempty"`
}

// Rubric is a judge's instructions and the verdict it declares. Reason asks the judge to
// justify its verdict, which is off unless declared: a reason's length survives erasure
// in the token count.
type Rubric struct {
	Instructions string `json:"instructions"`
	Output       Output `json:"output"`
	Reason       bool   `json:"reason,omitempty"`
}

const (
	maxValues       = 11
	minCategories   = 2
	maxCategories   = 10
	maxInstructions = 16 << 10
)

// A category is an identifier rather than prose, so it can be parsed without judgment.
var categoryPattern = regexp.MustCompile(`^[a-z][a-z0-9_]{0,31}$`)

var errInvalidRubric = errors.New("judge: invalid rubric")

// ParseRubric reads a rubric, refusing unknown fields, trailing data and any declaration
// the platform could not present as a closed list of codes.
func ParseRubric(raw []byte) (Rubric, error) {
	if err := strictJSON(raw); err != nil {
		return Rubric{}, fmt.Errorf("%w: %v", errInvalidRubric, err)
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.DisallowUnknownFields()
	var r Rubric
	if err := dec.Decode(&r); err != nil {
		return Rubric{}, fmt.Errorf("%w: %v", errInvalidRubric, err)
	}
	if dec.More() {
		return Rubric{}, fmt.Errorf("%w: data after the rubric", errInvalidRubric)
	}
	if err := r.validate(); err != nil {
		return Rubric{}, fmt.Errorf("%w: %v", errInvalidRubric, err)
	}
	return r, nil
}

func (r Rubric) validate() error {
	if r.Instructions == "" || len(r.Instructions) > maxInstructions {
		return fmt.Errorf("instructions must be 1 to %d bytes", maxInstructions)
	}
	switch o := r.Output; o.Type {
	case OutputPassFail:
		if declaresRange(o) || o.Categories != nil || o.Passing != nil {
			return errors.New("pass_fail declares nothing else")
		}
		return nil
	case OutputScore:
		return validScore(o)
	case OutputCategory:
		return validCategories(o)
	default:
		return fmt.Errorf("unknown output type %q", o.Type)
	}
}

// scoreWidth is high minus low for low < high, exact for any two ints: the unsigned
// difference wraps the way the signed one would overflow, and the true difference always
// fits in it.
func scoreWidth(low, high int) uint64 {
	return uint64(high) - uint64(low)
}

// declaresRange is whether any of a score's fields is present, zero included.
func declaresRange(o Output) bool {
	return o.Min != nil || o.Max != nil || o.Threshold != nil
}

func validScore(o Output) error {
	if o.Categories != nil || o.Passing != nil {
		return errors.New("a score declares no categories")
	}
	if o.Min == nil || o.Max == nil || o.Threshold == nil {
		return errors.New("a score declares min, max and threshold")
	}
	low, high, threshold := *o.Min, *o.Max, *o.Threshold
	if low >= high || scoreWidth(low, high) >= maxValues {
		return fmt.Errorf("a score has 2 to %d values", maxValues)
	}
	if threshold < low || threshold > high {
		return errors.New("the threshold is within the range")
	}
	return nil
}

func validCategories(o Output) error {
	if declaresRange(o) {
		return errors.New("a category declares no range")
	}
	if len(o.Categories) < minCategories || len(o.Categories) > maxCategories {
		return fmt.Errorf("%d to %d categories", minCategories, maxCategories)
	}
	declared := make(map[string]bool, len(o.Categories))
	for _, c := range o.Categories {
		if !categoryPattern.MatchString(c) || declared[c] {
			return fmt.Errorf("category %q is not a new identifier", c)
		}
		declared[c] = true
	}
	if len(o.Passing) == 0 {
		return errors.New("at least one category passes")
	}
	for _, p := range o.Passing {
		if !declared[p] {
			return fmt.Errorf("passing category %q is not declared", p)
		}
	}
	return nil
}

// Canonical is the rubric as one spelling, so the same declaration has one digest.
func (r Rubric) Canonical() []byte {
	b, err := json.Marshal(r)
	if err != nil {
		// A struct of strings, ints and a bool always marshals.
		panic(fmt.Sprintf("judge: marshal rubric: %v", err))
	}
	return b
}

// Digest is the rubric's version: its instructions and its whole declaration, hashed.
func (r Rubric) Digest() string {
	sum := sha256.Sum256(r.Canonical())
	return "sha256:" + hex.EncodeToString(sum[:])
}

// Option is one declared value, the fixed-width code the judge answers it with, and
// whether it passes.
type Option struct {
	Code   byte
	Value  string
	Passes bool
}

// Options are the declared values as codes A, B, C… in the rubric's order, and none for a
// rubric that is not valid: a range nobody checked could wrap and never end.
func (r Rubric) Options() []Option {
	if r.validate() != nil {
		return nil
	}
	var values []string
	var passes []bool
	switch o := r.Output; o.Type {
	case OutputPassFail:
		values, passes = []string{"pass", "fail"}, []bool{true, false}
	case OutputScore:
		// By count, never by value: a range ending at the largest int would wrap.
		for i := uint64(0); i <= scoreWidth(*o.Min, *o.Max); i++ {
			v := *o.Min + int(i)
			values, passes = append(values, strconv.Itoa(v)), append(passes, v >= *o.Threshold)
		}
	case OutputCategory:
		passing := make(map[string]bool, len(o.Passing))
		for _, p := range o.Passing {
			passing[p] = true
		}
		for _, c := range o.Categories {
			values, passes = append(values, c), append(passes, passing[c])
		}
	}
	out := make([]Option, len(values))
	for i := range values {
		out[i] = Option{Code: byte('A' + i), Value: values[i], Passes: passes[i]}
	}
	return out
}
